void TasMdkGenerator::structureFieldClass(
    cursiv::TextBuilder& out, const Structure& type,
    std::span<const Field* const> fields) const {
  const std::string_view className = type.name;
  const auto copies = [&] {
    for (const auto* field : fields)
      out.line("    ", field->name, " = other.", field->name, ";");
  };

  out.line("template<bool ...Opts>");
  out.line("struct _", className,
           " : public ::TasMdk::Types::StructureType<Opts...>");
  out.open("{");
  out.line("// the equivalent raw_type");
  out.line("using raw_type = ", fqn(&type), ";");
  out.line();
  out.line("// constructor");
  out.line("_", className,
           "(const std::string& name, const std::string& description,");
  out.write(R"(        Smp::IObject *parent, Smp::ViewKind view,
        const Smp::Publication::ITypeRegistry *type_registry, Smp::Uuid typeUuid,
        const raw_type &default_value = raw_type{}) :
)");
  {
    const auto initializers = out.indented(8);
    out.write(
        "::TasMdk::Types::StructureType<Opts...>(name, description, parent, "
        "view, type_registry->GetType(typeUuid))");
    for (const auto* field : fields) {
      out.line(",");
      out.line("/// ", field->name, " initialization");
      out.write(field->name, "{\"", field->name, "\", ", description(*field),
                ", this, ", viewKind(*field, "view"), ", type_registry, ",
                uuid(field->type.get()), ", default_value.", field->name, "}");
    }
    out.line(" {");
  }
  out.line("}");
  out.line();
  out.line("// copy operator");
  out.line("_", className, " & operator=(const _", className, " &other)");
  out.line("{");
  copies();
  out.line("    return *this;");
  out.line("}");
  out.line();
  out.line("// copy operator from raw_type");
  out.line("_", className, " & operator=(const raw_type &other)");
  out.line("{");
  copies();
  out.line("    return *this;");
  out.line("}");
  out.line();
  out.line("// convert to raw_type");
  out.line("operator raw_type() const noexcept");
  out.line("{");
  out.line("    return {", cursiv::joined(fields, ", ", &Field::name), "};");
  out.line("}");
  for (const auto* field : fields) {
    comment(out, *field);
    out.line(isMutable(*field) ? "mutable " : "",
             "typename ::TasMdk::", fieldWrapper(*field), "::in<Opts...>",
             fieldQualifiers(*field), "::type ", field->name, ";");
  }
  out.close("};");
}

std::string TasMdkGenerator::fieldType(const Type* type) const {
  if (!type) return {};
  const auto* parent = cursiv::ast_cast<const NamedElement>(type->parent);
  if (!parent) return {};
  return fqn(parent)
         + "::" + (cursiv::ast_cast<const SimpleType>(type) ? "" : "_")
         + std::string(type->name);
}

std::string TasMdkGenerator::fieldWrapper(const Field& field) const {
  const auto* type = field.type.get();
  if (cursiv::ast_cast<const Structure>(type))
    return "StructureField<" + fieldType(type) + ">";
  if (cursiv::ast_cast<const Array>(type))
    return "ArrayField<" + fieldType(type) + ">";
  return "SimpleField<" + fqn(type) + ">";
}

std::string TasMdkGenerator::fieldQualifiers(const Field& field) {
  std::string result;
  if (!isState(field)) result += "::transient";
  if (isInput(field)) result += "::input";
  if (isOutput(field)) result += "::output";
  if (attributeIsTrue(field, "Attributes.Failure")) result += "::failure";
  if (attributeIsTrue(field, "Attributes.Forcible")) result += "::forcible";
  if (attributeIsTrue(field, "TasMdk.OfInput")) result += "::of_input";
  if (attributeIsTrue(field, "TasMdk.OfOutput")) result += "::of_output";
  if (attributeIsTrue(field, "TasMdk.OfFailure")) result += "::of_failure";
  return result;
}

