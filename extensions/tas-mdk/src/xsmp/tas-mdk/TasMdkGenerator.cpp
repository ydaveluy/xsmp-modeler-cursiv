void TasMdkGenerator::generateEnumerationSourceGen(
    cursiv::TextBuilder& out, const Enumeration& type) const {
  const auto typeUuid = uuid(&type);
  out.open("void _Register_", type.name,
           "(::Smp::Publication::ITypeRegistry* registry) {");
  out.open("auto *type = registry->AddEnumerationType(");
  out.line("\"", type.name, "\", // Name");
  out.line(description(type), ", // Description");
  out.line("#if ECSS_SMP_VERSION < 202503L");
  out.line(typeUuid, ", // UUID");
  out.line("sizeof(", fqn(&type), ") // Size");
  out.line("#else");
  out.line(typeUuid, " // UUID");
  out.line("#endif");
  out.close(");");
  out.line();
  addLiterals(out, type);
  out.close("}");
}

void TasMdkGenerator::generatePackageHeader(cursiv::TextBuilder& out,
                                            const Catalogue& catalogue) const {
  const auto file = std::string(catalogueFileName(catalogue)) + ".h";
  const auto guard = includeGuard(std::string(catalogue.name));
  const std::string_view name = catalogue.name;

  notice(out, catalogue);
  fileBanner(out, file, shortBannerSeparator);
  out.line("/// @file ", file);
  out.line(autoGeneratedLine);
  out.line();
  out.line("#ifndef ", guard);
  out.line("#define ", guard);
  out.line();
  out.write(
      R"(// ----------------------------------------------------------------------------
// --------------------------------- Includes ---------------------------------
// ----------------------------------------------------------------------------
#include <Smp/ISimulator.h>
#include <Smp/Publication/ITypeRegistry.h>
#include <Smp/Version.h>

// Entry points for static library
extern "C" {
)");
  out.line("    /// Initialise Package ", name, ".");
  out.write(R"(    /// @param simulator Simulator for registration of factories.
    /// @param typeRegistry Type Registry for registration of types.
    /// @return True if initialisation was successful, false otherwise.
)");
  out.line("    bool Initialise_", name, "(");
  out.write(R"(        ::Smp::ISimulator* simulator,
        ::Smp::Publication::ITypeRegistry* typeRegistry);

)");
  out.line("    /// Finalise Package ", name, ".");
  out.write(
      R"(    /// @return True if finalisation was successful, false otherwise.
    #if ECSS_SMP_VERSION < 202503L
)");
  out.line("    bool Finalise_", name, "();");
  out.line("    #else");
  out.line("    bool Finalise_", name, "(::Smp::ISimulator *simulator);");
  out.line("    #endif");
  out.line("}");
  out.line();
  out.line("#endif // ", guard);
}

void TasMdkGenerator::generatePackageSource(cursiv::TextBuilder& out,
                                            const Catalogue& catalogue) const {
  const auto deps = dependentPackages(catalogue);
  const auto file = std::string(catalogueFileName(catalogue)) + ".cpp";
  const std::string_view name = catalogue.name;

  notice(out, catalogue);
  fileBanner(out, file, bannerSeparator);
  out.line("/// @file ", file);
  out.line(autoGeneratedLine);
  out.line();
  includes(out, packageSourceIncludes(catalogue));
  out.line();
  out.write(
      R"(// -----------------------------------------------------------------------------
// ----------------------------- Global variables ------------------------------
// -----------------------------------------------------------------------------

namespace {
/// Simulators set.
std::unordered_set<::Smp::ISimulator*> simulators { };
} // namespace


// -----------------------------------------------------------------------------
// --------------------------- Initialise Function -----------------------------
// -----------------------------------------------------------------------------

extern "C"
{
)");
  out.line("    /// Initialise Package ", name, ".");
  out.write(R"(    /// @param simulator Simulator for registration of factories.
    /// @param typeRegistry Type Registry for registration of types.
    /// @return True if initialisation was successful, false otherwise.
)");
  out.line("    bool Initialise_", name, "(");
  out.write(R"(            ::Smp::ISimulator* simulator,
            ::Smp::Publication::ITypeRegistry* typeRegistry) {
        // check simulator validity
        if (!simulator) {
            return false;
        }
        // avoid double initialisation
        if (!::simulators.emplace(simulator).second) {
            return true;
        }
)");
  {
    const auto body = out.indented(8);
    out.line();
    initialiseDependencies(out, deps);
    out.line();
    registerTypes(out, catalogue);
    out.line();
    registerComponents(out, catalogue);
  }
  out.line();
  out.write(R"(        return true;
    }
}

// ---------------------------------------------------------------------------------
// ---------------------------- Finalise Function ------------------------------
// ---------------------------------------------------------------------------------

extern "C"
{
)");
  out.line("    /// Finalise Package ", name, ".");
  out.write(
      R"(    /// @return True if finalisation was successful, false otherwise.
    #if ECSS_SMP_VERSION < 202503L
)");
  out.line("    bool Finalise_", name, "() {");
  out.write(R"(        // avoid double finalisation
        if (::simulators.empty()) {
            return true;
        }
        ::simulators.clear();

)");
  {
    const auto body = out.indented(8);
    finaliseDependencies(out, deps, "");
  }
  out.line("    }");
  out.line("    #else");
  out.line("    bool Finalise_", name, "(::Smp::ISimulator *simulator) {");
  out.write(R"(        // avoid double finalisation
        if (::simulators.empty()) {
            return true;
        }
        // check simulator validity
        if (!simulator) {
            return false;
        }
        // avoid double finalisation
        if (!::simulators.erase(simulator)) {
            return true;
        }
)");
  {
    const auto body = out.indented(8);
    finaliseDependencies(out, deps, "simulator");
  }
  out.write(R"(    }
    #endif
}
)");
}

void TasMdkGenerator::generateDynamicPackageSource(
    cursiv::TextBuilder& out, const Catalogue& catalogue) const {
  const auto catalogueFile = catalogueFileName(catalogue);
  const auto file = std::string(catalogueFile) + ".pkg.cpp";
  const std::string_view name = catalogue.name;

  notice(out, catalogue);
  fileBanner(out, file, bannerSeparator);
  out.line("/// @file ", file);
  out.line(autoGeneratedLine);
  out.line();
  out.write(
      R"(// -----------------------------------------------------------------------------
// --------------------------------- Includes ----------------------------------
// -----------------------------------------------------------------------------
)");
  out.line("#include <", catalogueFile, ".h>");
  out.write(R"(#include <Smp/ISimulator.h>
#include <Smp/Publication/ITypeRegistry.h>

#ifdef WIN32
#define DLL_EXPORT __declspec(dllexport) // %RELAX<mconst> Visual Studio requires a define
#else
#define DLL_EXPORT
#endif

// -----------------------------------------------------------------------------
// -------------------------- Initialise Function ------------------------------
// -----------------------------------------------------------------------------

extern "C" {
)");
  out.line("    /// Global Initialise function of Package ", name, ".");
  out.write(R"(    /// @param simulator Simulator for registration of factories.
    /// @param typeRegistry Type Registry for registration of types.
    /// @return True if initialisation was successful, false otherwise.
    DLL_EXPORT bool Initialise(
            ::Smp::ISimulator* simulator,
            ::Smp::Publication::ITypeRegistry* typeRegistry) {
)");
  out.line("        return Initialise_", name, "(simulator, typeRegistry);");
  out.write(R"(    }
}

// -----------------------------------------------------------------------------
// ---------------------------- Finalise Function ------------------------------
// -----------------------------------------------------------------------------

extern "C" {
)");
  out.line("    /// Global Finalise function of Package ", name, ".");
  out.write(R"(    /// @param simulator Simulator.
    /// @return True if finalisation was successful, false otherwise.
    #if ECSS_SMP_VERSION < 202503L
    DLL_EXPORT bool Finalise(::Smp::ISimulator*) {
)");
  out.line("        return Finalise_", name, "();");
  out.write(R"(    }
    #else
    DLL_EXPORT bool Finalise(::Smp::ISimulator* simulator) {
)");
  out.line("        return Finalise_", name, "(simulator);");
  out.write(R"(    }
    #endif
}

// -----------------------------------------------------------------------------
// ---------------------------- GetSmpVersion Function -------------------------
// -----------------------------------------------------------------------------

extern "C" {
)");
  out.line("    /// Global GetSmpVersion function of Package ", name, ".");
  out.write(R"(    /// @return the package smp version.
    DLL_EXPORT uint64_t GetSmpVersion() {
        return ECSS_SMP_VERSION;
    }
}
)");
}

std::vector<CppGenerator::Include> TasMdkGenerator::sourceIncludesComponent(
    const Component& type) const {
  std::vector<Include> result{std::string("Smp/Version.h")};
  for (const auto* element : type.elements)
    appendTo(result, sourceIncludes(*element));
  return result;
}

std::vector<CppGenerator::Include> TasMdkGenerator::sourceIncludesEnumeration(
    const Enumeration& /*type*/) const {
  return {std::string("Smp/Version.h"),
          std::string("Smp/Publication/IEnumerationType.h")};
}

std::vector<CppGenerator::Include> TasMdkGenerator::sourceIncludesOperation(
    const Operation& element) const {
  std::vector<Include> result{
      std::string("Smp/Publication/IPublishOperation.h")};
  if (const auto* returned = element.returnParameter)
    appendTo(result, sourceIncludesParameter(*returned));
  for (const auto* parameter : element.parameter)
    appendTo(result, sourceIncludesParameter(*parameter));
  return result;
}

void TasMdkGenerator::registerModel(cursiv::TextBuilder& out,
                                    const Model& model) const {
  const auto qualified = fqn(&model);
  out.line("// Register factory for Model ", model.name);
  out.open("simulator->RegisterFactory(new ::TasMdk::Factory(");
  out.line("\"", model.name, "\", // Name");
  out.line(description(model), ", // Description");
  out.line("simulator, // parent");
  out.line(uuid(&model), ", // UUID");
  out.line("\"", qualified, "\", // Type name");
  out.write(R"([](::Smp::String8 name,
    ::Smp::String8 description,
    ::Smp::IObject* parent,
    ::Smp::Publication::ITypeRegistry* type_registry) {
)");
  out.line("    return new ", qualified,
           "(name, description, parent, type_registry);");
  out.write(R"(}, // Instantiation callback
typeRegistry // Type Registry
)");
  out.close("));");
}

