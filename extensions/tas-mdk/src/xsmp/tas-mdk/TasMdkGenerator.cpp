constexpr std::string_view bannerSeparator =
    "// -----------------------------------------------------------------------"
    "------";

constexpr std::string_view shortBannerSeparator =
    "// -----------------------------------------------------------------------"
    "----";

template <class T>
bool attributeIsTrue(const T& element, std::string_view id) {
  return attributeBoolValue(element, id).value_or(false);
}

