void TasMdkGenerator::generateComponentHeader(cursiv::TextBuilder& out,
                                              const Component& type) const {
  const std::string_view className = type.name;
  comment(out, type);
  out.line("class ", className, ": public ", className, "Gen {");
  out.line("public:");
  if (std::ranges::any_of(type.elements, [](const NamedElement* element) {
        const auto* operation = cursiv::ast_cast<const Operation>(element);
        return operation && isConstructorAttribute(*operation);
      }))
    out.line("    using ", className, "Gen::", className, "Gen;");
  out.write(R"(    /// Constructor setting name, description and parent.
    /// @param name Name of new model instance.
    /// @param description Description of new model instance.
    /// @param parent Parent of new model instance.
    /// @param type_registry Reference to global type registry.
)");
  out.line("    ", className, "(");
  out.write(R"(            ::Smp::String8 name,
            ::Smp::String8 description,
            ::Smp::IObject* parent,
            ::Smp::Publication::ITypeRegistry* type_registry);

    /// Virtual destructor to release memory.
)");
  out.line("    ~", className, "() noexcept override = default;");
  out.line();
  out.open();
  declareMembers(out, type.elements, Visibility::Public);
  out.close("};");
}

void TasMdkGenerator::generateComponentSource(cursiv::TextBuilder& out,
                                              const Component& type,
                                              bool gen) const {
  const std::string_view className = type.name;
  const auto genName = name(type.name, true);
  out.line(className, "::", className, "(");
  out.write(R"(        ::Smp::String8 name,
        ::Smp::String8 description,
        ::Smp::IObject* parent,
        ::Smp::Publication::ITypeRegistry* type_registry)
)");
  out.line("        : ", genName, "::", genName,
           "(name, description, parent, type_registry) {");
  out.line("    // Publish_Callback = std::bind(&", className,
           "::_publishHook, this, std::placeholders::_1);");
  out.line();
  out.line("    // Configure_Callback = std::bind(&", className,
           "::_configureHook, this, std::placeholders::_1, "
           "std::placeholders::_2);");
  out.line();
  out.line("    // Connect_Callback = std::bind(&", className,
           "::_connectHook, this, std::placeholders::_1);");
  out.line();
  out.line("    // Disconnect_Callback = std::bind(&", className,
           "::_disconnectHook, this);");
  out.line("}");
  out.line();
  defineMembers(out, type.elements, gen);
}

void TasMdkGenerator::generateComponentHeaderGen(cursiv::TextBuilder& out,
                                                 const Component& type,
                                                 bool gen) const {
  const auto className = name(type.name, gen);

  openComponentClass(out, type, gen);
  out.open();
  out.line();
  declareMembersGen(out, type.elements, Visibility::Private, gen);
  out.line();
  out.write(
      R"(// ------------------------------------------------------------------------------------
// ------------------------- Constructors/Destructor -------------------------
// ------------------------------------------------------------------------------------
public:
/// Constructor setting name, description and parent.
/// @param name Name of new model instance.
/// @param description Description of new model instance.
/// @param parent Parent of new model instance.
/// @param type_registry Reference to global type registry.
)");
  out.line(className, "(");
  out.write(R"(        ::Smp::String8 name,
        ::Smp::String8 description,
        ::Smp::IObject* parent,
        ::Smp::Publication::ITypeRegistry* type_registry);

/// Virtual destructor to release memory.
)");
  out.line("~", className, "() override;");
  out.line();
  out.line("static ::TasMdk::Request::Handler<", className,
           ">::CollectionType requestHandlers;");
  out.line();
  out.write(
      R"(// ----------------------------------------------------------------------------------
// ------------------------------- IComponent --------------------------------
// ----------------------------------------------------------------------------------

/// Publish fields, operations and properties of the model.
/// @param receiver Publication receiver.
void Publish(::Smp::IPublication* receiver) override;

/// Request for configuration.
/// @param logger Logger to use for log messages during Configure().
/// @param linkRegistry Link Registry to use for registration of
///         links created during Configure() or later.
void Configure(::Smp::Services::ILogger* logger, ::Smp::Services::ILinkRegistry* linkRegistry) override;

/// Connect model to simulator.
/// @param simulator Simulation  Environment  that  hosts the model.
///
void Connect(
    ::Smp::ISimulator* simulator) override;

/// Disconnect model to simulator.
/// @throws Smp::InvalidComponentState
void Disconnect() override;

/// Return the Universally Unique Identifier of the Model.
/// @return  Universally Unique Identifier of the Model.
const Smp::Uuid& GetUuid() const override;

/// Invoke the operation for the given request.
/// @param request Request object to invoke.
void Invoke(::Smp::IRequest* request) override;

protected:
/// It populates the static map of request handler to implement the invoke function.
/// @param bluePrint an object to use as blue print if needed
/// @param handlers the map to be populated.
template <typename _Type>
static void PopulateRequestHandlers(_Type* bluePrint, typename ::TasMdk::Request::Handler<_Type>::CollectionType& handlers);

private:
/// Callback for custom publication
std::function<void(::Smp::IPublication*)> Publish_Callback;
/// Callback for custom configuration
std::function<void(::Smp::Services::ILogger *, ::Smp::Services::ILinkRegistry*)> Configure_Callback;
/// Callback for custom connection
std::function<void(::Smp::ISimulator*)> Connect_Callback;
/// Callback for custom disconnection
std::function<void()> Disconnect_Callback;
)");
  out.close("};");
  out.line();
  out.line("template <typename _Type>");
  out.line("void ", className, "::PopulateRequestHandlers(");
  out.write(R"(    [[maybe_unused]] _Type* bluePrint,
    [[maybe_unused]] typename ::TasMdk::Request::Handler<_Type>::CollectionType& handlers)
{
)");
  out.open();
  // What cannot be invoked has no handler: it would not compile.
  for (const auto* element : type.elements)
    if (const auto* operation = cursiv::ast_cast<const Operation>(element);
        operation && isInvokable(*operation)) {
      requestHandlerOperation(out, *operation);
      out.line();
    }
  for (const auto* element : type.elements)
    if (const auto* property = cursiv::ast_cast<const Property>(element);
        property && isInvokable(*property)) {
      requestHandlerProperty(out, *property);
      out.line();
    }
  out.close("}");
}

std::string TasMdkGenerator::componentBase(const Component& type) const {
  return type.base.has_value()
             ? fqn(type.base->get())
             : "::TasMdk::" + std::string(componentKind(type));
}

void TasMdkGenerator::generateComponentSourceGen(cursiv::TextBuilder& out,
                                                 const Component& type,
                                                 bool gen) const {
  const auto className = name(type.name, gen);
  const auto base = componentBase(type);

  out.line("::TasMdk::Request::Handler<", className, ">::CollectionType ",
           className, "::requestHandlers;");
  out.line();
  out.open("void ", className,
           "::Configure(::Smp::Services::ILogger* logger, "
           "::Smp::Services::ILinkRegistry* linkRegistry) {");
  out.line("// Call base implementation first");
  out.line(base, "::Configure(logger, linkRegistry);");
  out.open("if (Configure_Callback) {");
  out.line("Configure_Callback(logger, linkRegistry);");
  out.close("}");
  out.close("}");
  out.line();
  out.open("void ", className, "::Connect(::Smp::ISimulator* simulator) {");
  out.line("// Call mdk implementation first");
  out.line(base, "::Connect(simulator);");
  out.open("if (Connect_Callback) {");
  out.line("Connect_Callback(simulator);");
  out.close("}");
  out.close("}");
  out.line();
  out.open("void ", className, "::Disconnect() {");
  out.open("if (Disconnect_Callback) {");
  out.line("Disconnect_Callback();");
  out.close("}");
  out.line(
      "// Call parent implementation last, to remove references to the "
      "Simulator and its services");
  out.line(base, "::Disconnect();");
  out.close("}");
  out.line();
  out.line(className, "::", className, "(");
  out.write(R"(    ::Smp::String8 name,
    ::Smp::String8 description,
    ::Smp::IObject* parent,
    ::Smp::Publication::ITypeRegistry* type_registry)
    : // Base class initialization
)");
  out.open();
  out.write(base, "(name, description, parent, type_registry)");
  initializeMembers(out, type.elements, gen);
  out.line();
  out.close("{");
  out.line("}");
  out.line();
  out.open(className, "::~", className, "() {");
  finalizeMembers(out, type.elements);
  out.close("}");
  out.line();
  out.line("void ", className, "::Publish(::Smp::IPublication* receiver) {");
  out.line("    // Call base class implementation first");
  out.line("    ", base, "::Publish(receiver);");
  out.line();
  out.line("    if (Publish_Callback) {");
  out.line("        Publish_Callback(receiver);");
  out.line("    }");
  out.line();
  out.line("    // Populate the request handlers (only once)");
  out.line("    if (requestHandlers.empty()) {");
  out.line("        PopulateRequestHandlers<", className,
           ">(this, requestHandlers);");
  out.line("    }");
  out.line();
  out.open();
  publishMembers(out, type.elements);
  out.close("}");
  out.line();
  out.line("void ", className, "::Invoke(::Smp::IRequest* request) {");
  out.write(R"(    if (request == nullptr) {
        return;
    }
    #if ECSS_SMP_VERSION < 202503L
    auto handler = requestHandlers.find(request->GetOperationName());
    #else
    auto handler = requestHandlers.find(request->GetName());
    #endif
    if (handler != requestHandlers.end()) {
        handler->second(*this, request);
    } else {
        // pass the request down to the base model
)");
  out.line("        ", base, "::Invoke(request);");
  out.line("    }");
  out.line("}");
  out.line();
  out.open("const ::Smp::Uuid& ", className, "::GetUuid() const {");
  out.line("return Uuid_", type.name, ";");
  out.close("}");
  out.line();
  defineMembersGen(out, type.elements, gen);
}

void TasMdkGenerator::requestHandlerOperation(cursiv::TextBuilder& out,
                                              const Operation& op) const {
  const auto* returned = op.returnParameter;
  out.open("if (handlers.find(\"", op.name, "\") == handlers.end()) {");
  out.open("handlers[\"", op.name,
           "\"] = [](_Type & component, [[maybe_unused]] ::Smp::IRequest* "
           "request) {");
  for (const auto* parameter : op.parameter) initParameter(out, *parameter);
  out.line();
  out.line("/// Invoke ", op.name);
  if (returned)
    out.write("request->SetReturnValue({",
              primitiveTypeKind(returned->type.get()), ", ");
  out.write("component.", operationName(op), "(");
  std::string_view separator;
  for (const auto* parameter : op.parameter) {
    if (isOptionalPointer(*parameter))
      out.write(separator, "has_", parameter->name, " ? &p_", parameter->name,
                " : nullptr");
    else
      out.write(separator, isByPointer(*parameter) ? "&" : "", "p_",
                parameter->name);
    separator = ", ";
  }
  out.line(")", returned ? "})" : "", ";");
  for (const auto* parameter : op.parameter) setParameter(out, *parameter);
  out.close("};");
  out.close("}");
}

void TasMdkGenerator::initParameter(cursiv::TextBuilder& out,
                                    const Parameter& parameter) const {
  if (isOptionalPointer(parameter)) {
    const std::string_view name = parameter.name;
    const auto read = parameter.direction != "out";
    out.line(read ? "bool" : "const bool", " has_", name,
             " = request->GetParameterIndex(\"", name, "\") >= 0;");
    out.line(fqn(parameter.type.get()), " p_", name, "{};");
    if (!read) return;
    out.line("::Smp::AnySimple storage_", name, ";");
    out.open("if (has_", name, ") {");
    out.line("::TasMdk::Request::initParameter(storage_", name, ", request, \"",
             name, "\", ", primitiveTypeKind(parameter.type.get()), ", true);");
    out.line("has_", name, " = storage_", name,
             ".GetType() != ::Smp::PrimitiveTypeKind::PTK_None;");
    out.line("if (has_", name, ") { p_", name, " = static_cast<",
             fqn(parameter.type.get()), ">(storage_", name, "); }");
    out.close("}");
    return;
  }
  const auto* value = parameter.default_;
  out.write(fqn(parameter.type.get()), " p_", parameter.name);
  if (value) out.write(directListInitializer(value));
  out.line(";");
  if (parameter.direction == "out") return;
  out.line("::TasMdk::Request::initParameter(p_", parameter.name,
           ", request, \"", parameter.name, "\", ",
           primitiveTypeKind(parameter.type.get()), value ? ", true" : "",
           ");");
}

void TasMdkGenerator::setParameter(cursiv::TextBuilder& out,
                                   const Parameter& parameter) const {
  if (parameter.direction != "out" && parameter.direction != "inout") return;
  const auto optional = isOptionalPointer(parameter);
  out.line(
      optional ? "if (has_" : "", optional ? parameter.name : "",
      optional ? ") { " : "", "::TasMdk::Request::setParameter(request, \"",
      parameter.name, "\", {", primitiveTypeKind(parameter.type.get()), ", p_",
      parameter.name,
      cursiv::ast_cast<const String>(parameter.type.get()) ? ".data()" : "",
      "});", optional ? " }" : "");
}

void TasMdkGenerator::requestHandlerProperty(cursiv::TextBuilder& out,
                                             const Property& property) const {
  const auto access = getAccessKind(property).value_or(AccessKind::ReadWrite);
  const auto kind = primitiveTypeKind(property.type.get());
  const std::string_view propertyName = property.name;
  // A local of the name of a parameter of the handler would not compile.
  const auto local = propertyName == "component" || propertyName == "request"
                         ? std::string_view("value")
                         : propertyName;
  if (access != AccessKind::WriteOnly) {
    out.open("if (handlers.find(\"get_", propertyName,
             "\") == handlers.end()) {");
    out.open("handlers[\"get_", propertyName,
             "\"] = [](_Type & component, ::Smp::IRequest* request) {");
    out.line("/// Invoke get_", propertyName);
    out.line("request->SetReturnValue({", kind, ", component.get_",
             propertyName, "()});");
    out.close("};");
    out.close("}");
    out.line();
  }
  if (access != AccessKind::ReadOnly) {
    out.open("if (handlers.find(\"set_", propertyName,
             "\") == handlers.end()) {");
    out.open("handlers[\"set_", propertyName,
             "\"] = [](_Type & component, ::Smp::IRequest* request) {");
    out.line("/// Invoke set_", propertyName);
    // A String8 points into the value of the request, which a local keeps.
    if (isString8(property.type.get())) {
      const auto storage = "storage_" + std::string(propertyName);
      out.line("::Smp::AnySimple ", storage, ";");
      out.line("::TasMdk::Request::initParameter(", storage, ", request, \"",
               propertyName, "\", ", kind, ");");
      out.line("auto ", local, " = static_cast<", fqn(property.type.get()),
               ">(", storage, ");");
    } else {
      out.line(fqn(property.type.get()), " ", local, ";");
      out.line("::TasMdk::Request::initParameter(", local, ", request, \"",
               propertyName, "\", ", kind, ");");
    }
    out.line("component.set_", propertyName, "(", local, ");");
    out.close("};");
    out.close("}");
  }
}

bool TasMdkGenerator::isCdkField(const Field& field) const {
  if (!cursiv::ast_cast<const Component>(field.parent)
      || isStaticAttribute(field)
      || cursiv::ast_cast<const Class>(field.type.get()))
    return false;
  if (isInput(field) || isOutput(field)) return true;
  for (const auto attribute :
       {"Attributes.Failure", "Attributes.Forcible", "TasMdk.OfInput",
        "TasMdk.OfOutput", "TasMdk.OfFailure"})
    if (attributeIsTrue(field, attribute)) return true;
  return false;
}

std::vector<CppGenerator::Include> TasMdkGenerator::headerIncludesField(
    const Field& field) const {
  auto result = GapPatternCppGenerator::headerIncludesField(field);
  if (isCdkField(field)) result.emplace_back(std::string("TasMdk/Field.h"));
  return result;
}

void TasMdkGenerator::declareFieldGen(cursiv::TextBuilder& out,
                                      const Field& field, bool gen) const {
  if (!isCdkField(field)) {
    GapPatternCppGenerator::declareFieldGen(out, field, gen);
    return;
  }
  comment(out, field);
  out.line(isMutable(field) ? "mutable " : "",
           "typename ::TasMdk::", fieldWrapper(field), fieldQualifiers(field),
           "::type ", field.name, ";");
}

void TasMdkGenerator::initializeField(cursiv::TextBuilder& out,
                                      const Field& field) const {
  if (!isCdkField(field)) {
    GapPatternCppGenerator::initializeField(out, field);
    return;
  }
  const auto typeUuid = uuid(field.type.get());
  out.line("// Field ", field.name);
  out.open(field.name, "{");
  out.line("\"", field.name, "\", // Name");
  out.line(description(field), ", // Description");
  out.line("this, // Parent");
  out.line(viewKind(field), ", // View Kind");
  out.line("type_registry, // Type Registry");
  if (field.default_) {
    out.line(typeUuid, ", // Type UUID");
    out.line(expression(field.default_), " // Default value");
  } else {
    out.line(typeUuid, " // Type UUID");
  }
  out.close().write("}");
}

