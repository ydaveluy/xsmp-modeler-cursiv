void TasMdkGenerator::generateArrayHeaderGen(cursiv::TextBuilder& out,
                                             const Array& type,
                                             bool gen) const {
  const auto simple =
      attributeBoolValue(type, "Attributes.SimpleArray")
          .value_or(cursiv::ast_cast<const SimpleType>(type.itemType.get())
                    != nullptr);
  const auto className = name(type.name, gen);
  const auto size = expression(type.size);
  comment(out, type);
  out.line("using ", className, " = ::TasMdk::Types::Array<",
           fqn(type.itemType.get()), ", ", size, ">;");
  out.line();
  uuidDeclaration(out, type);
  out.line();
  out.line("void _Register_", type.name,
           "(::Smp::Publication::ITypeRegistry* registry);");
  out.line();
  out.line("template<bool ...Opts>");
  out.line("using _", className,
           " = TasMdk::Types::", simple ? "SimpleArrayType" : "ArrayType", "<",
           fieldType(type.itemType.get()), ", ", size, ", Opts...>;");
}

